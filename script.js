let language = "fr";
const languageButtons = Array.from(document.querySelectorAll("[data-language]"));
const languageLocale = () => language === "fr" ? "fr-FR" : "en-US";
const number = (value, maximumFractionDigits = 0) => new Intl.NumberFormat(languageLocale(), { maximumFractionDigits }).format(value);

function updateCalculator() {
  const slider = document.getElementById("user-count");
  const usersOutput = document.getElementById("current-users");
  const gmvOutput = document.getElementById("gmv-result");
  const revenueOutput = document.getElementById("revenue-result");
  if (!slider || !usersOutput || !gmvOutput || !revenueOutput) return;

  const users = Number(slider.value);
  const annualOrders = 4;
  const averageBasket = 150000;
  const gmv = users * annualOrders * averageBasket;
  const unit = language === "fr" ? "Md" : "bn";
  usersOutput.textContent = number(users);
  gmvOutput.textContent = `${number(gmv / 1_000_000_000, 1)} ${unit} FCFA`;
  revenueOutput.textContent = `${number(gmv * 0.03 / 1_000_000)}–${number(gmv * 0.05 / 1_000_000)} M FCFA / ${language === "fr" ? "an" : "year"}`;
  slider.setAttribute("aria-valuetext", `${number(users)} ${copy[language]["calc.merchantsAria"]}`);

  const usersStat = document.querySelector(".proof-tile:nth-child(2) strong");
  const gmvStat = document.querySelector(".proof-tile:nth-child(3) strong");
  if (usersStat && users === 13000) usersStat.textContent = language === "fr" ? "13 000" : "13,000";
  if (gmvStat && users === 13000) gmvStat.textContent = language === "fr" ? "7,8 Md" : "7.8 bn";
  const pilotFactory = document.querySelector(".pilot-product > b");
  const pilotTotal = document.querySelector(".price-total > b");
  if (pilotFactory) pilotFactory.textContent = `${number(6426)} FCFA`;
  if (pilotTotal) pilotTotal.textContent = `${number(11000)} FCFA`;
}

